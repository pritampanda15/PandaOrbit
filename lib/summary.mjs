// ─────────────────────────────────────────────────────────────
//  PandaOrbit Work Summary & Local Docs Generator.
//
//  Synthesizes HabitBoard time logs + Orrery git/project state
//  + overrides.json personal notes into an executive daily or
//  weekly Work Summary in Markdown, Google-Docs-ready HTML,
//  and plain text.
// ─────────────────────────────────────────────────────────────

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const escHtml = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"
}[c]));

function fmtHrs(h) {
  const n = Number(h) || 0;
  if (n < 0.05) return "0.0h";
  return `${n.toFixed(2)}h`;
}

function fmtMins(m) {
  const n = Math.round(Number(m) || 0);
  if (n < 60) return `${n}m`;
  const h = Math.floor(n / 60);
  const rem = n % 60;
  return rem ? `${h}h ${rem}m` : `${h}h`;
}

function isoDateLocal(d = new Date()) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

export function generateWorkSummary({ report, tree, overrides = {}, range = "today" }) {
  const now = new Date();
  const dateIso = isoDateLocal(now);
  const rangeTitles = {
    today: `Daily Work Summary — ${report?.currentDate || dateIso}`,
    "7d": `Weekly Work Summary (Last 7 Days · Ending ${dateIso})`,
    "30d": `Monthly Work Summary (Last 30 Days · Ending ${dateIso})`,
    all: `Complete Work Summary (Through ${dateIso})`
  };
  const title = rangeTitles[range] || rangeTitles.today;
  const kpis = report?.kpis || {
    totalHoursToday: 0,
    productiveHoursToday: 0,
    dailyGoalHours: 4,
    goalProgressPct: 0,
    streakDays: 0,
    totalHoursRange: 0,
    topCategory: "N/A",
    avgDailyHours7d: 0,
    distractionPct: 0,
    focusScore: 0
  };

  // Collect Orrery projects + merge overrides + HabitBoard tracked project time
  const windowDays = range === "today" ? 1.5 : range === "7d" ? 7 : range === "30d" ? 30 : 9999;
  const projectTime = report?.projectTime || {};
  const projectHighlights = [];

  for (const dom of tree?.domains || []) {
    for (const proj of dom.children || []) {
      const ov = overrides[proj.key] || {};
      if (ov.hide) continue;
      const pt = projectTime[proj.name] || null;
      const trackedMin = range === "today"
        ? (pt?.minutesToday || 0)
        : range === "7d"
          ? (pt?.minutes7d || 0)
          : (pt?.minutesTotal || 0);
      const recentlyTouched = typeof proj.ageDays === "number" && proj.ageDays <= windowDays;
      const status = ov.status || proj.status;
      if (trackedMin > 0 || recentlyTouched || status === "active" || ov.note) {
        projectHighlights.push({
          name: ov.label || proj.name,
          domain: dom.name,
          status,
          branch: proj.branch || null,
          commits: proj.commits || 0,
          lastCommitMsg: proj.lastCommitMsg || null,
          ageDays: proj.ageDays,
          trackedMin,
          note: ov.note || null,
          tagline: proj.tagline || null
        });
      }
    }
  }

  projectHighlights.sort((a, b) =>
    (b.trackedMin - a.trackedMin) ||
    ((a.ageDays ?? 999) - (b.ageDays ?? 999))
  );

  const cats = report?.categorySummary || [];
  const topActs = (report?.topActivities || []).slice(0, 10);
  const topCatsText = cats.slice(0, 2).map((c) => `${c.category} (${fmtHrs(c.hours)}, ${c.pct}%)`).join(" and ");
  const activeProjCount = projectHighlights.filter((p) => p.status === "active" || p.trackedMin > 0).length;

  const narrative = kpis.totalHoursRange > 0
    ? `Logged ${fmtHrs(kpis.totalHoursRange)} of tracked work with a ${kpis.focusScore.toFixed(1)}% focus score (${kpis.distractionPct.toFixed(1)}% distraction share)${topCatsText ? `, led by ${topCatsText}` : ""}. Active momentum spanned ${activeProjCount} project${activeProjCount === 1 ? "" : "s"} with a ${kpis.streakDays || 0}-day focus streak.`
    : `No HabitBoard screen sessions were logged in this window yet, with ${activeProjCount} active workspace project${activeProjCount === 1 ? "" : "s"} scanned across ${(tree?.domains || []).length} domain${(tree?.domains || []).length === 1 ? "" : "s"}.`;

  const notesList = projectHighlights.filter((p) => p.note).slice(0, 8);

  // ── 1. Markdown Output ──────────────────────────────────────
  const md = [];
  md.push(`# ${title}`);
  md.push(`*Generated by PandaOrbit on ${now.toLocaleString()}*`);
  md.push("");
  md.push("## Executive Summary");
  md.push(narrative);
  md.push("");
  md.push("## Key Metrics");
  md.push("| Metric | Value |");
  md.push("|---|---|");
  md.push(`| Total Hours (${range}) | ${fmtHrs(kpis.totalHoursRange)} |`);
  md.push(`| Deep Focus Today | ${fmtHrs(kpis.productiveHoursToday)} / ${kpis.dailyGoalHours}h goal (${kpis.goalProgressPct}%) |`);
  md.push(`| Focus Score | ${kpis.focusScore.toFixed(1)}% |`);
  md.push(`| Distraction Share | ${kpis.distractionPct.toFixed(1)}% |`);
  md.push(`| 7-Day Daily Average | ${fmtHrs(kpis.avgDailyHours7d)} |`);
  md.push(`| Active Streak | ${kpis.streakDays || 0} day${kpis.streakDays === 1 ? "" : "s"} |`);
  md.push(`| Dominant Category | ${kpis.topCategory} |`);
  md.push("");

  md.push("## Project Progress");
  if (projectHighlights.length) {
    for (const p of projectHighlights.slice(0, 12)) {
      const meta = [
        p.domain,
        p.status,
        p.trackedMin > 0 ? `${fmtMins(p.trackedMin)} tracked` : null,
        p.branch ? `branch \`${p.branch}\`` : null,
        p.commits ? `${p.commits} commits` : null
      ].filter(Boolean).join(" · ");
      md.push(`- **${p.name}** (${meta})`);
      if (p.note) md.push(`  - *Note:* ${p.note}`);
      if (p.lastCommitMsg) md.push(`  - *Latest commit:* ${p.lastCommitMsg}`);
      else if (p.tagline) md.push(`  - ${p.tagline}`);
    }
  } else {
    md.push("- No project activity recorded in this window.");
  }
  md.push("");

  if (cats.length) {
    md.push("## Time Allocation by Category");
    md.push("| Category | Hours | Share |");
    md.push("|---|---:|---:|");
    for (const c of cats) {
      md.push(`| ${c.category} | ${c.hours.toFixed(2)}h | ${c.pct}% |`);
    }
    md.push("");
  }

  if (topActs.length) {
    md.push("## Top Activities");
    for (const a of topActs) {
      const proj = a.matchedProject ? ` [${a.matchedProject}]` : "";
      md.push(`- **${a.windowTitle}** — ${a.minutes.toFixed(1)} min (${a.category} · ${a.appName})${proj}`);
    }
    md.push("");
  }

  if (notesList.length) {
    md.push("## Pinned Notes & Next Steps");
    for (const p of notesList) {
      md.push(`- **${p.name}:** ${p.note}`);
    }
    md.push("");
  }

  const markdown = md.join("\n");

  // ── 2. Google-Docs-Ready Clean Semantic HTML ────────────────
  const html = `<!doctype html>
<html>
<head><meta charset="utf-8"><title>${escHtml(title)}</title></head>
<body style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Arial,sans-serif;color:#1d1d1f;line-height:1.55;max-width:780px;margin:24px auto;">
  <h1 style="margin-bottom:4px;">${escHtml(title)}</h1>
  <p style="color:#6e6e73;font-size:13px;margin-top:0;">Generated by PandaOrbit on ${escHtml(now.toLocaleString())}</p>

  <h2>Executive Summary</h2>
  <p>${escHtml(narrative)}</p>

  <h2>Key Metrics</h2>
  <table border="1" cellspacing="0" cellpadding="8" style="border-collapse:collapse;border-color:#d2d2d7;width:100%;">
    <tr style="background:#f5f5f7;"><th align="left">Metric</th><th align="left">Value</th></tr>
    <tr><td>Total Hours (${escHtml(range)})</td><td>${escHtml(fmtHrs(kpis.totalHoursRange))}</td></tr>
    <tr><td>Deep Focus Today</td><td>${escHtml(fmtHrs(kpis.productiveHoursToday))} / ${escHtml(kpis.dailyGoalHours)}h goal (${escHtml(kpis.goalProgressPct)}%)</td></tr>
    <tr><td>Focus Score</td><td>${escHtml(kpis.focusScore.toFixed(1))}%</td></tr>
    <tr><td>Distraction Share</td><td>${escHtml(kpis.distractionPct.toFixed(1))}%</td></tr>
    <tr><td>7-Day Daily Average</td><td>${escHtml(fmtHrs(kpis.avgDailyHours7d))}</td></tr>
    <tr><td>Active Streak</td><td>${escHtml(kpis.streakDays || 0)} days</td></tr>
    <tr><td>Dominant Category</td><td>${escHtml(kpis.topCategory)}</td></tr>
  </table>

  <h2>Project Progress</h2>
  ${projectHighlights.length ? `<ul>${projectHighlights.slice(0, 12).map((p) => {
    const meta = [p.domain, p.status, p.trackedMin > 0 ? `${fmtMins(p.trackedMin)} tracked` : null, p.branch ? `branch ${p.branch}` : null].filter(Boolean).join(" · ");
    const sub = [p.note ? `Note: ${p.note}` : null, p.lastCommitMsg ? `Latest commit: ${p.lastCommitMsg}` : p.tagline].filter(Boolean).join(" — ");
    return `<li><strong>${escHtml(p.name)}</strong> <span style="color:#6e6e73">(${escHtml(meta)})</span>${sub ? `<br><span>${escHtml(sub)}</span>` : ""}</li>`;
  }).join("")}</ul>` : `<p>No project activity recorded in this window.</p>`}

  ${cats.length ? `
    <h2>Time Allocation by Category</h2>
    <table border="1" cellspacing="0" cellpadding="8" style="border-collapse:collapse;border-color:#d2d2d7;width:100%;">
      <tr style="background:#f5f5f7;"><th align="left">Category</th><th align="right">Hours</th><th align="right">Share</th></tr>
      ${cats.map((c) => `<tr><td>${escHtml(c.category)}</td><td align="right">${c.hours.toFixed(2)}h</td><td align="right">${c.pct}%</td></tr>`).join("")}
    </table>
  ` : ""}

  ${topActs.length ? `
    <h2>Top Activities</h2>
    <ul>${topActs.map((a) => `<li><strong>${escHtml(a.windowTitle)}</strong> — ${a.minutes.toFixed(1)} min (${escHtml(a.category)} · ${escHtml(a.appName)})${a.matchedProject ? ` [${escHtml(a.matchedProject)}]` : ""}</li>`).join("")}</ul>
  ` : ""}
</body>
</html>`;

  // ── 3. Clean Plain Text (for Google Docs REST API / Apps Script) ──
  const plainLines = [
    title,
    `Generated by PandaOrbit on ${now.toLocaleString()}`,
    "",
    "EXECUTIVE SUMMARY",
    narrative,
    "",
    "KEY METRICS",
    `• Total Hours (${range}): ${fmtHrs(kpis.totalHoursRange)}`,
    `• Deep Focus Today: ${fmtHrs(kpis.productiveHoursToday)} / ${kpis.dailyGoalHours}h (${kpis.goalProgressPct}%)`,
    `• Focus Score: ${kpis.focusScore.toFixed(1)}% (Distraction: ${kpis.distractionPct.toFixed(1)}%)`,
    `• 7-Day Average: ${fmtHrs(kpis.avgDailyHours7d)} | Active Streak: ${kpis.streakDays || 0} days`,
    `• Dominant Activity: ${kpis.topCategory}`,
    ""
  ];
  if (projectHighlights.length) {
    plainLines.push("PROJECT PROGRESS");
    for (const p of projectHighlights.slice(0, 12)) {
      const extra = [p.trackedMin > 0 ? `${fmtMins(p.trackedMin)} tracked` : null, p.branch ? `branch ${p.branch}` : null].filter(Boolean).join(", ");
      plainLines.push(`• ${p.name} [${p.domain} · ${p.status}${extra ? ` · ${extra}` : ""}]`);
      if (p.note) plainLines.push(`    Note: ${p.note}`);
      if (p.lastCommitMsg) plainLines.push(`    Latest commit: ${p.lastCommitMsg}`);
    }
    plainLines.push("");
  }
  if (cats.length) {
    plainLines.push("TIME ALLOCATION BY CATEGORY");
    for (const c of cats) plainLines.push(`• ${c.category}: ${c.hours.toFixed(2)}h (${c.pct}%)`);
    plainLines.push("");
  }
  if (topActs.length) {
    plainLines.push("TOP ACTIVITIES");
    for (const a of topActs) plainLines.push(`• ${a.windowTitle} — ${a.minutes.toFixed(1)} min (${a.category})`);
    plainLines.push("");
  }

  return {
    title,
    dateIso,
    range,
    narrative,
    markdown,
    html,
    plainText: plainLines.join("\n"),
    meta: {
      totalHours: kpis.totalHoursRange,
      focusScore: kpis.focusScore,
      streakDays: kpis.streakDays || 0,
      projectCount: projectHighlights.length,
      categoryCount: cats.length
    }
  };
}

export async function saveSummaryReport({ outDir, summary, format = "md" }) {
  const reportsDir = join(outDir, "reports");
  await mkdir(reportsDir, { recursive: true });
  const ext = format === "html" ? "html" : "md";
  const filename = `work-summary-${summary.dateIso}-${summary.range}.${ext}`;
  const filePath = join(reportsDir, filename);
  await writeFile(filePath, ext === "html" ? summary.html : summary.markdown, "utf8");
  return { filePath, filename, reportsDir };
}
